MANIFESTS = ("/pyproject.toml", "/package.json", "/go.mod", "/Cargo.toml")


def show(*parts) -> None:
    """Prints evidence without failing on characters the console encoding can't represent (e.g. emoji on cp1252)."""
    text = " ".join(str(p) for p in parts)
    encoding = sys.stdout.encoding or "utf-8"
    print(text.encode(encoding, errors="replace").decode(encoding), flush=True)


class Conversation:
    def __init__(self, conv_id: str):
        self.conv_id, self.history = conv_id, []

    async def say(self, text: str) -> str:
        response = await cs.generate_chat_response(text, self.history, self.conv_id)
        if response.startswith("TITLE:"):
            response = response.split("\n\n", 1)[-1]
        assert "(Reference: " not in response, f"the AI service failed (see the backend log): {response}"
        self.history += [{"role": "user", "text": text}, {"role": "assistant", "text": response}]
        s = self.state()
        show(f"\n===== USER: {text}\n----- ASSISTANT:\n{response}\n----- stage: "
             f"{(s['project'] or {}).get('workflow_stage')} | outdated: {store.outdated_items(s)}")
        return response

    def state(self) -> dict:
        s = store.get_workflow_state(self.conv_id)
        assert not s.get("error"), s
        return s


def tree_at(project: str, repo: str, version: str, version_type: str = "branch") -> dict:
    with live.client() as c:
        r = c.get(f"{live.repo_url(project, repo)}/items", params={
            "scopePath": "/", "recursionLevel": "Full", "versionDescriptor.version": version,
            "versionDescriptor.versionType": version_type, "api-version": "7.1"})
        r.raise_for_status()
        return {i["path"] for i in r.json()["value"] if not i.get("isFolder")}


def assert_commands_only(repo: dict) -> None:
    """The saved base structure is exactly the recorded commands' output; the commands are allow-listed CLIs."""
    commands = repo["scaffold_commands"]
    assert commands, "the structure must be generated by commands"
    for item in commands:
        assert item["command"].split()[0] in ALLOWED_COMMANDS, item
    show("[evidence] commands:", json.dumps(commands))


def assert_pushed_byte_for_byte(project: str, repo: dict) -> list:
    """Commit 1 = generator output, commit 2 = requested changes; the branch holds exactly the reviewed files."""
    name = repo["repo_name"]
    commits = live.list_commits(project, name, "main")
    show("[evidence] commits:", [(c["commitId"][:8], c["comment"].splitlines()[0]) for c in commits])
    generator_commit = commits[-1]
    assert generator_commit["comment"].startswith(rsa.SCAFFOLD_COMMIT_MESSAGE)
    assert tree_at(project, name, generator_commit["commitId"], "commit") == {f["path"] for f in repo["scaffold_structure"]}
    assert tree_at(project, name, "main") == {f["path"] for f in repo["structure"]}
    for f in repo["structure"]:
        assert live.get_file_bytes(project, name, f["path"], "main") == decode_file(f), f["path"]
    return commits


async def setup_until_repository(chat: Conversation, project_name: str, repo_name: str) -> str:
    await chat.say("The TRD looks good. Let's proceed with repository setup.")
    assert chat.state()["project"]["workflow_stage"] == store.STAGE_PROJECT_REVIEW
    await chat.say(f"Please change the project name to '{project_name}' and keep the description.")
    assert chat.state()["project"]["project_name"] == project_name
    await chat.say("Looks good, create the Azure DevOps project.")
    s = chat.state()
    assert s["project"]["ado_project_id"], "ADO project was not created"
    await chat.say(f"Please call the repository '{repo_name}' instead.")
    assert chat.state()["repository"]["repo_name"] == repo_name
    response = await chat.say("Approved, create the repository.")
    return response


@pytest.fixture
def memory_db(monkeypatch):
    fake = FakeSupabase()
    monkeypatch.setattr(store, "client_factory", lambda: fake)
    return fake


def run_scenario(coro_factory):
    project_name = live.unique("DevFoundry-E2E")
    holder = {}
    try:
        asyncio.run(coro_factory(project_name, holder))
    finally:
        project_id = holder.get("project_id") or live.wait_for_project(project_name, timeout=5)
        if project_id and os.getenv("ADO_E2E_KEEP") != "1":
            assert project_name.startswith("DevFoundry-E2E-")
            show(f"[cleanup] delete ADO project {project_name}: HTTP {live.delete_project(project_id)}")



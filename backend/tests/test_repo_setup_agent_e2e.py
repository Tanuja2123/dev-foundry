# Scenario 1: CLI application, no stack mentioned
# ---------------------------------------------------------------------------

CLI_ANSWERS = """Here are my answers:
1. Purpose: "taskflow", a command-line tool that lets a developer manage their personal to-do list from the terminal; tasks are stored in a local file in the user's home folder.
2. Users: a single role, the individual developer who installs the tool. There are no admins and no other roles.
3. Capabilities: add a task with a title, optional priority (low/medium/high) and optional due date; list tasks filtered by status, priority or due date; mark a task as done; edit or delete a task; export the list to a Markdown file.
4. Platform: cross-platform terminal (Windows, macOS, Linux). No sign-in, no accounts - everything is local.
5. Success criteria: every command answers in under 200 ms for 1,000 tasks; installable with a single command; 90% unit-test coverage.
6. Business rules: a due date cannot be in the past; task titles are unique among open tasks. Scale: up to 10,000 tasks. No integrations. Must work offline. Out of scope: syncing, a GUI, team features.
Please don't ask further questions - make reasonable assumptions for anything else."""


def test_scenario_1_cli_application_without_stack(memory_db):
    async def scenario(project_name, holder):
        chat = Conversation(live.unique("e2e-cli"))
        await chat.say("I want to build a command-line tool for developers.")
        assert not (chat.state()["project"] or {}).get("prd"), "a vague request must lead to questions, not a PRD"
        await chat.say(CLI_ANSWERS)
        assert chat.state()["project"]["prd"], "PRD expected after the answers"
        await chat.say("Yes, please create the TRD.")
        trd = chat.state()["project"]["trd"]
        assert trd, "TRD expected"
        show("[evidence] TRD stack:", json.dumps(trd, ensure_ascii=False)[:600])

        response = await setup_until_repository(chat, project_name, "taskflow-cli")
        s = chat.state()
        holder["project_id"] = s["project"]["ado_project_id"]
        repo = s["repository"]
        assert repo["status"] == store.REPO_STRUCTURE_REVIEW and repo["structure"] == repo["scaffold_structure"]
        assert_commands_only(repo)
        paths = [f["path"] for f in repo["structure"]]
        assert any(p in MANIFESTS for p in paths) or any(p.endswith(".csproj") and p.count("/") == 1 for p in paths), \
            "a single CLI app must be generated at the repository root"
        assert not any(p.startswith(("/frontend/", "/backend/")) for p in paths)
        assert cs.render_structure_for_display(s) in response                         # shown == stored
        assert live.get_repo(project_name, "taskflow-cli").get("defaultBranch") is None  # nothing pushed yet

        # The user asks for extra files on top of the generated structure
        await chat.say("Please add a docs/usage.md file with a short usage guide and a GitHub Actions CI workflow "
                       "at .github/workflows/ci.yml that runs the tests.")
        repo = chat.state()["repository"]
        changes = layer_changes(repo["scaffold_structure"], repo["structure"])
        show("[evidence] requested changes:", changes)
        assert {"/docs/usage.md", "/.github/workflows/ci.yml"} <= set(changes["add"])
        assert not changes["delete"], "generated files must stay"

        response = await chat.say("Looks good, push the structure to the main branch.")
        s = chat.state()
        repo = s["repository"]
        assert repo["status"] == store.REPO_PUSHED and s["project"]["workflow_stage"] == store.STAGE_COMPLETE
        commits = assert_pushed_byte_for_byte(project_name, repo)
        assert len(commits) == 2 and set(changes["add"]) <= tree_at(project_name, "taskflow-cli", "main")
        assert repo["commit_id"][:7] in response or repo["commit_id"] in response
        show(live.render_tree({f["path"] for f in repo["structure"]}))

    run_scenario(scenario)



"""
Opt-in end-to-end tests of the complete flow through the real Orchestrator + child agents (LLM), the real generator
commands (npx / uv) and real Azure DevOps:

  description -> (clarifying questions) -> PRD -> TRD -> project proposal -> ADO project -> repository
  -> structure generated by CLI commands -> review (changes / different approach) -> push (generator commit + changes)

Scenario 1: a CLI application, no stack named by the user (the TRD picks it; generated at the repository root).
Scenario 2: a React + FastAPI full-stack application (frontend/ + backend/ generated by commands), the user rejects the
            TypeScript frontend, the structure is regenerated and a requested document is added.

Run (from backend/, venv active):
    $env:ADO_E2E_TESTS="1"; pytest tests/test_repo_setup_agent_e2e.py -m e2e -s

Each scenario creates a "DevFoundry-E2E-<id>" ADO project and deletes it at the end (ADO_E2E_KEEP=1 keeps it).
Project/Repository rows live in an in-memory database (tests/fake_supabase.py), so no Supabase rows or migrations are
needed; generate_chat_response is called directly with the conversation history.
"""

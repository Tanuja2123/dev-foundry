# Scenario 2 without the LLM: the same tool calls the Repo Setup Agent makes, with real generators and real ADO
# ---------------------------------------------------------------------------

def test_scenario_2_tool_flow_without_llm(memory_db):
    """create project/repo -> generate React (TS) + FastAPI -> user rejects TS -> regenerate (JS) -> add a requested
    document -> push (generator commit + changes commit) -> change after the push (follow-up commit)."""
    project_name = live.unique("DevFoundry-E2E")
    conv_id = live.unique("e2e-tools")
    store.ensure_project(conv_id)
    tools = {t.name: getattr(t, "func", t) for t in rsa.build_repo_setup_tools(conv_id)}
    project_id = None
    try:
        created = tools["create_ado_project"](project_name=project_name, project_description="ShelfShare E2E")
        assert created["status"] == "success", created
        project_id = created["id"]
        assert tools["create_ado_repository"](project_id_or_name=project_name, repository_name="shelfshare")["status"] == "success"

        first = tools["scaffold_repository_structure"](commands=[
            {"command": "npx --yes create-vite@latest frontend --template react-ts"},
            {"command": "uv init --app --vcs none --name backend backend"},
            {"command": "uv add --no-sync fastapi[standard]", "cwd": "backend"}])
        assert first["status"] == "success", first
        assert "/frontend/src/App.tsx" in first["paths"] and "/backend/pyproject.toml" in first["paths"]

        second = tools["scaffold_repository_structure"](commands=[
            {"command": "npx --yes create-vite@latest frontend --template react"},
            {"command": "uv init --app --vcs none --name backend backend"},
            {"command": "uv add --no-sync fastapi[standard]", "cwd": "backend"}])
        assert second["status"] == "success" and "/frontend/src/App.jsx" in second["paths"]
        assert not any(p.endswith(".tsx") for p in second["paths"])

        added = tools["update_repository_structure"](upsert_files=[
            {"path": "/docs/architecture.md", "content": "# Architecture\n\n- frontend/: React SPA\n- backend/: FastAPI API\n"}])
        assert added["changes_on_top_of_generated_files"] == {"add": ["/docs/architecture.md"], "edit": [], "delete": []}
        show(cs.render_structure_for_display(store.get_workflow_state(conv_id)))

        pushed = tools["push_repository_structure"]()
        assert pushed["status"] == "success", pushed
        repo = store.get_workflow_state(conv_id)["repository"]
        commits = assert_pushed_byte_for_byte(project_name, repo)
        assert len(commits) == 2 and commits[0]["comment"] == rsa.CHANGES_COMMIT_MESSAGE

        tools["update_repository_structure"](upsert_files=[{"path": "/CONTRIBUTING.md", "content": "# Contributing\n"}])
        follow_up = tools["push_repository_structure"](commit_message="docs: add contributing guide")
        assert follow_up["status"] == "success" and follow_up["push_type"] == "follow-up commit"
        assert follow_up["changes"] == {"add": ["/CONTRIBUTING.md"], "edit": [], "delete": []}
        assert len(live.list_commits(project_name, "shelfshare", "main")) == 3
    finally:
        if project_id and os.getenv("ADO_E2E_KEEP") != "1":
            show(f"[cleanup] delete ADO project {project_name}: HTTP {live.delete_project(project_id)}")

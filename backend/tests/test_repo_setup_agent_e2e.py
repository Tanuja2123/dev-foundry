# Scenario 2: React + FastAPI full stack, user rejects the generated approach
# ---------------------------------------------------------------------------

FULLSTACK_DESCRIPTION = """I want to build "ShelfShare", a web application for a community library where members lend books to each other.
- Users and roles: members (list their own books, browse and request books, approve or decline requests for their books) and librarians (manage members, resolve disputes, see lending statistics).
- Capabilities: members can add/edit/remove their books, search the catalog by title/author/genre, request a loan, approve/decline incoming requests and mark a book as returned; librarians can deactivate members, view overdue loans and export monthly statistics.
- Platform: responsive web app in the browser; members and librarians sign in with email and password.
- Success criteria: 300 active members in the first 3 months, search results in under 1 second, overdue loans under 5%.
- Tech: a React single-page frontend and a Python FastAPI backend with PostgreSQL.
- Rules: a loan lasts 14 days, a member can have at most 3 open loans. Out of scope: payments, mobile apps.
Please create the PRD; make reasonable assumptions for anything that is missing."""


def test_scenario_2_react_fastapi_full_stack(memory_db):
    async def scenario(project_name, holder):
        chat = Conversation(live.unique("e2e-fullstack"))
        await chat.say(FULLSTACK_DESCRIPTION)
        if not (chat.state()["project"] or {}).get("prd"):
            await chat.say("Please make reasonable assumptions for anything that is missing and create the PRD now.")
        assert chat.state()["project"]["prd"], "PRD expected"
        await chat.say("Yes, please create the TRD.")
        trd_text = json.dumps(chat.state()["project"]["trd"]).lower()
        assert "react" in trd_text and "fastapi" in trd_text

        response = await setup_until_repository(chat, project_name, "shelfshare")
        s = chat.state()
        holder["project_id"] = s["project"]["ado_project_id"]
        repo = s["repository"]
        assert_commands_only(repo)
        paths = [f["path"] for f in repo["structure"]]
        frontend = {p.split("/")[1] for p in paths if p.endswith("/package.json") and p.count("/") == 2}
        backend = {p.split("/")[1] for p in paths if p.endswith("/pyproject.toml") and p.count("/") == 2}
        assert frontend and backend and frontend != backend, f"expected separate frontend/backend parts: {paths}"
        assert any(p.endswith(".tsx") for p in paths), "TypeScript React frontend expected first"
        assert repo["structure"] == repo["scaffold_structure"]
        assert cs.render_structure_for_display(s) in response
        first_commands = repo["scaffold_commands"]

        # The user does not accept the approach: technology change -> TRD update -> structure regenerated
        await chat.say("I don't want this approach for the frontend. Use plain JavaScript instead of TypeScript for "
                       "the React frontend.")
        s = chat.state()
        assert store.STRUCTURE_OUTDATED in store.outdated_items(s), "the TRD should have been updated"
        await chat.say("Update the repository structure to reflect the latest TRD, and also add a docs/architecture.md "
                       "file that briefly describes the frontend and backend layers.")
        repo = chat.state()["repository"]
        assert_commands_only(repo)
        assert repo["scaffold_commands"] != first_commands, "the structure must be regenerated with new commands"
        paths = [f["path"] for f in repo["structure"]]
        assert not any(p.endswith((".tsx", ".ts")) and "/src/" in p for p in paths), f"JavaScript frontend expected: {paths}"
        assert any(p.endswith(".jsx") for p in paths)
        changes = layer_changes(repo["scaffold_structure"], repo["structure"])
        show("[evidence] requested changes:", changes)
        assert changes["add"] == ["/docs/architecture.md"] and not changes["edit"] and not changes["delete"]

        response = await chat.say("Looks good, push it to main.")
        repo = chat.state()["repository"]
        assert repo["status"] == store.REPO_PUSHED
        commits = assert_pushed_byte_for_byte(project_name, repo)
        assert len(commits) == 2
        show(live.render_tree({f["path"] for f in repo["structure"]}))

    run_scenario(scenario)


